export const getRoomBySlug = (slug) => {
  const clean = (slug || '').replace(/^rooms\//, '');
  return roomsData.find(
    (room) =>
      room.slug === clean ||
      room.id === clean ||
      room.slug === `${clean}-room` ||
      room.slug === clean.replace(/s$/, '')
  );
};
