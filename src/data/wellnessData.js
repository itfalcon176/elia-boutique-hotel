export const getFacilityBySlug = (slug) => {
  if (!slug) return wellnessData.facilities[0];
  const clean = slug.toLowerCase().replace(/^\/|\/$/g, '').replace(/^facilities\//, '');
  
  return wellnessData.facilities.find(
    (f) => f.slug === clean || f.id === clean || (f.aliases && f.aliases.includes(clean))
  ) || wellnessData.facilities[0];
};

